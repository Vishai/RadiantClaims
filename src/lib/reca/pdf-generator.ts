/**
 * RECA PDF Generator
 * Generates a comprehensive data summary PDF that users can reference
 * while filling out the official RECA Downwinder Claim Form
 */

import { PDFDocument, rgb, StandardFonts } from 'pdf-lib';
import * as fs from 'fs';
import * as path from 'path';
import { RECAFormData, RECASupportingForms, RelationshipType } from './types';

// Color scheme matching our UI
const COLORS = {
  sage: rgb(0.38, 0.44, 0.35), // #617059
  terracotta: rgb(0.82, 0.49, 0.37), // #D17D5E
  cream: rgb(0.98, 0.96, 0.91), // #FAF5E9
  black: rgb(0, 0, 0),
  gray: rgb(0.4, 0.4, 0.4),
  white: rgb(1, 1, 1),
};

interface PDFGeneratorOptions {
  formData: Partial<RECAFormData>;
  supportingForms: Partial<RECASupportingForms>;
  sessionId: string;
}

export class RECAPDFGenerator {
  private pdfDoc!: PDFDocument;
  private currentPage: any;
  private currentY: number = 0;
  private pageWidth: number = 612; // US Letter width in points
  private pageHeight: number = 792; // US Letter height in points
  private margin: number = 50;
  private lineHeight: number = 15;
  private font: any;
  private boldFont: any;
  private formData: Partial<RECAFormData>;
  private supportingForms: Partial<RECASupportingForms>;

  constructor(options: PDFGeneratorOptions) {
    this.formData = options.formData;
    this.supportingForms = options.supportingForms;
  }

  async generate(): Promise<Uint8Array> {
    this.pdfDoc = await PDFDocument.create();
    this.font = await this.pdfDoc.embedFont(StandardFonts.Helvetica);
    this.boldFont = await this.pdfDoc.embedFont(StandardFonts.HelveticaBold);

    // Generate cover page
    await this.generateCoverPage();

    // Generate main form data pages
    await this.generateFormDataPages();

    // Generate supporting forms pages
    await this.generateSupportingFormsPages();

    // Generate instructions page
    await this.generateInstructionsPage();

    return await this.pdfDoc.save();
  }

  private async generateCoverPage() {
    this.addNewPage();

    // Title
    this.currentY = this.pageHeight - 100;
    this.drawText('RECA Downwinder Claim', {
      x: this.margin,
      y: this.currentY,
      size: 28,
      font: this.boldFont,
      color: COLORS.terracotta,
    });

    this.currentY -= 30;
    this.drawText('Your Form Data Summary', {
      x: this.margin,
      y: this.currentY,
      size: 20,
      font: this.boldFont,
      color: COLORS.sage,
    });

    this.currentY -= 60;
    this.drawText('Generated by RadiantClaims', {
      x: this.margin,
      y: this.currentY,
      size: 12,
      color: COLORS.gray,
    });

    this.currentY -= 20;
    this.drawText(`Date: ${new Date().toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    })}`, {
      x: this.margin,
      y: this.currentY,
      size: 12,
      color: COLORS.gray,
    });

    // Instructions box
    this.currentY -= 60;
    this.drawBox({
      x: this.margin,
      y: this.currentY - 150,
      width: this.pageWidth - (2 * this.margin),
      height: 150,
      fillColor: rgb(0.95, 0.95, 0.95),
      borderColor: COLORS.sage,
    });

    this.currentY -= 20;
    this.drawText('How to Use This Document:', {
      x: this.margin + 10,
      y: this.currentY,
      size: 14,
      font: this.boldFont,
      color: COLORS.sage,
    });

    this.currentY -= 25;
    const instructions = [
      '1. Review this data summary carefully to ensure all information is correct',
      '2. Use this summary to fill out the official RECA Downwinder Claim Form',
      '3. Sign the official form with a wet (handwritten) signature',
      '4. Mail the completed official form to the Department of Justice',
      '5. Keep this summary for your records',
    ];

    instructions.forEach((instruction) => {
      this.drawText(instruction, {
        x: this.margin + 20,
        y: this.currentY,
        size: 11,
        color: COLORS.black,
      });
      this.currentY -= 20;
    });

    // Important notice
    this.currentY -= 40;
    this.drawBox({
      x: this.margin,
      y: this.currentY - 80,
      width: this.pageWidth - (2 * this.margin),
      height: 80,
      fillColor: rgb(1, 0.95, 0.9),
      borderColor: COLORS.terracotta,
    });

    this.currentY -= 20;
    this.drawText('IMPORTANT:', {
      x: this.margin + 10,
      y: this.currentY,
      size: 12,
      font: this.boldFont,
      color: COLORS.terracotta,
    });

    this.currentY -= 20;
    this.drawText('This is NOT the official form. You must print and complete the official', {
      x: this.margin + 10,
      y: this.currentY,
      size: 10,
      color: COLORS.black,
    });

    this.currentY -= 15;
    this.drawText('RECA Downwinder Claim Form included in your download package.', {
      x: this.margin + 10,
      y: this.currentY,
      size: 10,
      color: COLORS.black,
    });
  }

  private async generateFormDataPages() {
    // Part 1: Filer Information
    if (this.formData.part_1) {
      this.addNewPage();
      this.addSectionHeader('Part 1: Your Information (Filer)');

      this.addField('First Name', this.formData.part_1.firstName);
      this.addField('Middle Name', this.formData.part_1.middleName);
      this.addField('Last Name', this.formData.part_1.lastName);
      this.addField('Former Names', this.formData.part_1.formerNames);
      this.addField('Social Security Number', this.formData.part_1.ssn);
      this.addField('Date of Birth', this.formatDate(this.formData.part_1.dob));
      this.addField('Mailing Address', this.formData.part_1.mailingAddress);
      this.addField('City', this.formData.part_1.city);
      this.addField('State', this.formData.part_1.state);
      this.addField('ZIP Code', this.formData.part_1.zipCode);
      this.addField('Phone (Day)', this.formData.part_1.phoneDay);
      this.addField('Phone (Evening)', this.formData.part_1.phoneEvening);
      this.addField('Email', this.formData.part_1.email);
      this.addField('Residence Address (if different)', this.formData.part_1.residenceAddress);
      this.addField('Tribal Affiliation', this.formData.part_1.tribalAffiliation);
      this.addField('Tribal Census Number', this.formData.part_1.tribalCensusNumber);
    }

    // Part 2: Claimant Information (if not self-filing)
    if (this.formData.part_2) {
      this.addSectionHeader('Part 2: Claimant Information (Person Who Became Ill)');

      this.addField('First Name', this.formData.part_2.firstName);
      this.addField('Middle Name', this.formData.part_2.middleName);
      this.addField('Last Name', this.formData.part_2.lastName);
      this.addField('Former Names', this.formData.part_2.formerNames);
      this.addField('Social Security Number', this.formData.part_2.ssn);
      this.addField('Date of Birth', this.formatDate(this.formData.part_2.dob));
      this.addField('Date of Death', this.formatDate(this.formData.part_2.dod));
    }

    // Part 3: Relationship
    if (this.formData.part_3) {
      this.addSectionHeader('Part 3: Relationship to Claimant');
      this.addField('Relationship', this.formData.part_3.relationship);
    }

    // Part 5: Surviving Spouse (if applicable)
    if (this.formData.part_5) {
      this.addSectionHeader('Part 5: Surviving Spouse Information');
      this.addField('Claimant Deceased', this.formData.part_5.claimantDeceased);
      this.addField('Married at Least One Year', this.formData.part_5.marriedOneYear);
      this.addField('Claimant Had Previous Marriages', this.formData.part_5.claimantPreviousMarriages);

      if (this.formData.part_5.claimantPreviousSpouses) {
        this.currentY -= 10;
        this.drawText('Previous Spouses of Claimant:', {
          x: this.margin + 10,
          y: this.currentY,
          size: 11,
          font: this.boldFont,
        });
        this.currentY -= 15;

        this.formData.part_5.claimantPreviousSpouses.forEach((spouse, index) => {
          this.drawText(`${index + 1}. ${spouse.spouseName}`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
          });
          this.currentY -= 15;
          this.drawText(`   Marriage: ${this.formatDate(spouse.marriageStart)} to ${this.formatDate(spouse.marriageEnd)}`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
            color: COLORS.gray,
          });
          this.currentY -= 20;
          this.checkPageBreak();
        });
      }

      this.addField('Filer Has Other Marriages', this.formData.part_5.filerOtherMarriages);
    }

    // Part 6: Surviving Child (if applicable)
    if (this.formData.part_6) {
      this.addSectionHeader('Part 6: Surviving Child Information');
      this.addField('Claimant Deceased', this.formData.part_6.claimantDeceased);
      this.addField('Claimant Ever Married', this.formData.part_6.claimantEverMarried);
      this.addField('Child Type', this.formData.part_6.childType);
      this.addField('Other Children Exist', this.formData.part_6.otherChildrenExist);

      if (this.formData.part_6.otherChildren) {
        this.currentY -= 10;
        this.drawText('Other Eligible Children:', {
          x: this.margin + 10,
          y: this.currentY,
          size: 11,
          font: this.boldFont,
        });
        this.currentY -= 15;

        this.formData.part_6.otherChildren.forEach((child, index) => {
          this.drawText(`${index + 1}. ${child.name}`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
          });
          this.currentY -= 15;
          if (child.currentAddress) {
            this.drawText(`   Address: ${child.currentAddress}`, {
              x: this.margin + 20,
              y: this.currentY,
              size: 10,
              color: COLORS.gray,
            });
            this.currentY -= 15;
          }
          this.currentY -= 5;
          this.checkPageBreak();
        });
      }
    }

    // Part 7: Other Relatives (if applicable)
    if (this.formData.part_7) {
      this.addSectionHeader('Part 7: Other Relatives Information');
      this.addField('Relationship Type', this.formData.part_7.relationshipType);
    }

    // Part 8: Exposure Information
    if (this.formData.part_8) {
      this.checkPageBreak(200); // Make sure we have room
      this.addSectionHeader('Part 8: Exposure Information');

      this.currentY -= 10;
      this.drawText('Exposure Options Selected:', {
        x: this.margin + 10,
        y: this.currentY,
        size: 11,
        font: this.boldFont,
      });
      this.currentY -= 15;

      this.formData.part_8.exposureOptions.forEach((option) => {
        const optionText = option === 'option_1a'
          ? 'Option 1A: Affected Areas (Idaho, New Mexico, Utah)'
          : option === 'option_1b'
          ? 'Option 1B: Arizona Counties'
          : 'Option 2: Nevada Counties';

        this.drawText(`• ${optionText}`, {
          x: this.margin + 20,
          y: this.currentY,
          size: 10,
        });
        this.currentY -= 20;
      });

      // Affected Areas
      if (this.formData.part_8.affectedAreas && this.formData.part_8.affectedAreas.length > 0) {
        this.currentY -= 10;
        this.drawText('Affected Areas (Idaho, New Mexico, Utah):', {
          x: this.margin + 10,
          y: this.currentY,
          size: 11,
          font: this.boldFont,
        });
        this.currentY -= 15;

        this.formData.part_8.affectedAreas.forEach((area, index) => {
          this.drawText(`${index + 1}. ${area.townCity}, ${area.state}`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
          });
          this.currentY -= 15;
          this.drawText(`   Time Period: ${area.timePeriod}`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
            color: COLORS.gray,
          });
          this.currentY -= 20;
          this.checkPageBreak();
        });
      }

      // Arizona Counties
      if (this.formData.part_8.arizonaCounties && this.formData.part_8.arizonaCounties.length > 0) {
        this.currentY -= 10;
        this.drawText('Arizona Counties:', {
          x: this.margin + 10,
          y: this.currentY,
          size: 11,
          font: this.boldFont,
        });
        this.currentY -= 15;

        this.formData.part_8.arizonaCounties.forEach((county, index) => {
          this.drawText(`${index + 1}. ${county.townCity}, ${county.county} County, Arizona`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
          });
          this.currentY -= 15;
          this.drawText(`   Time Period: ${county.timePeriod}`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
            color: COLORS.gray,
          });
          this.currentY -= 20;
          this.checkPageBreak();
        });
      }

      // Nevada Counties
      if (this.formData.part_8.nevadaCounties && this.formData.part_8.nevadaCounties.length > 0) {
        this.currentY -= 10;
        this.drawText('Nevada Counties:', {
          x: this.margin + 10,
          y: this.currentY,
          size: 11,
          font: this.boldFont,
        });
        this.currentY -= 15;

        this.formData.part_8.nevadaCounties.forEach((county, index) => {
          this.drawText(`${index + 1}. ${county.townCity}, ${county.county} County, Nevada`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
          });
          this.currentY -= 15;
          this.drawText(`   Time Period: ${county.timePeriod}`, {
            x: this.margin + 20,
            y: this.currentY,
            size: 10,
            color: COLORS.gray,
          });
          this.currentY -= 20;
          this.checkPageBreak();
        });
      }
    }

    // Part 9: Proof of Presence
    if (this.formData.part_9) {
      this.addSectionHeader('Part 9: Proof of Presence');
      this.addField('LDS Church Assistance Requested', this.formData.part_9.ldsChurchAssistance ? 'Yes' : 'No');
    }

    // Part 10: Compensable Diseases
    if (this.formData.part_10) {
      this.checkPageBreak(150);
      this.addSectionHeader('Part 10: Compensable Diseases');

      this.currentY -= 10;
      this.drawText('Diseases Selected:', {
        x: this.margin + 10,
        y: this.currentY,
        size: 11,
        font: this.boldFont,
      });
      this.currentY -= 15;

      this.formData.part_10.diseases.forEach((disease) => {
        const diseaseLabel = this.formatDiseaseName(disease);
        this.drawText(`• ${diseaseLabel}`, {
          x: this.margin + 20,
          y: this.currentY,
          size: 10,
        });
        this.currentY -= 18;
        this.checkPageBreak();
      });
    }

    // Part 11: Proof of Disease
    if (this.formData.part_11) {
      this.addSectionHeader('Part 11: Proof of Disease');
      this.addField('Medical Records Submitted', this.formData.part_11.medicalRecordsSubmitted ? 'Yes' : 'No');
      this.addField('Cancer Registry Authorization', this.formData.part_11.cancerRegistryAuthorization ? 'Yes' : 'No');
      this.addField('RESEP Assistance', this.formData.part_11.resepAssistance || 'Not specified');
      if (this.formData.part_11.resepClinicName) {
        this.addField('RESEP Clinic Name', this.formData.part_11.resepClinicName);
      }
    }

    // Part 12: Previous Payments
    if (this.formData.part_12) {
      this.addSectionHeader('Part 12: Previous Payments');
      this.addField('Previously Received Payment', this.formData.part_12.receivedPayment);
      if (this.formData.part_12.paymentDetails) {
        this.addField('Payment Details', this.formData.part_12.paymentDetails);
      }
      this.addField('EEOICPA Claim', this.formData.part_12.eeoicpaClaim);
    }

    // Part 13: Attorney Representation
    if (this.formData.part_13) {
      this.addSectionHeader('Part 13: Attorney Representation');
      this.addField('Has Attorney', this.formData.part_13.hasAttorney);
      if (this.formData.part_13.hasAttorney === 'YES') {
        this.addField('Attorney Name', `${this.formData.part_13.attorneyFirstName} ${this.formData.part_13.attorneyLastName}`);
        this.addField('Law Firm', this.formData.part_13.attorneyFirm);
        this.addField('Attorney Address', this.formData.part_13.attorneyAddress);
        this.addField('Attorney City, State, ZIP', `${this.formData.part_13.attorneyCity}, ${this.formData.part_13.attorneyState} ${this.formData.part_13.attorneyZip}`);
        this.addField('Attorney Phone', this.formData.part_13.attorneyPhone);
        this.addField('Attorney Email', this.formData.part_13.attorneyEmail);
      }
    }

    // Part 14: Attorney Acknowledgment
    if (this.formData.part_14) {
      this.addSectionHeader('Part 14: Attorney Acknowledgment');
      this.addField('Fee Type', this.formData.part_14.feeType === 'initial_2_percent' ? '2% (Initial Claim)' : '10% (Resubmission)');
      this.addField('Attorney Signature Date', this.formatDate(this.formData.part_14.attorneySignatureDate));
    }

    // Part 15: Legal Guardian
    if (this.formData.part_15) {
      this.addSectionHeader('Part 15: Legal Guardian Information');
      this.addField('Guardian Name', `${this.formData.part_15.guardianFirstName} ${this.formData.part_15.guardianMiddleName || ''} ${this.formData.part_15.guardianLastName}`.trim());
      this.addField('Guardian Address', this.formData.part_15.guardianAddress);
      this.addField('Guardian City, State, ZIP', `${this.formData.part_15.guardianCity}, ${this.formData.part_15.guardianState} ${this.formData.part_15.guardianZip}`);
      this.addField('Guardian Phone (Day)', this.formData.part_15.guardianPhoneDay);
      this.addField('Guardian Phone (Evening)', this.formData.part_15.guardianPhoneEvening);
      this.addField('Guardian Email', this.formData.part_15.guardianEmail);
    }

    // Part 16: Signature
    if (this.formData.part_16) {
      this.addSectionHeader('Part 16: Signature');
      this.addField('Signature Date', this.formatDate(this.formData.part_16.signatureDate));
      this.addField('Authorization Acknowledged', this.formData.part_16.authorizationAcknowledgment ? 'Yes' : 'No');
    }
  }

  private async generateSupportingFormsPages() {
    // Medical Information Release
    if (this.supportingForms.medicalInformationRelease) {
      this.addNewPage();
      this.addSectionHeader('Medical Information Release Form');

      const form = this.supportingForms.medicalInformationRelease;
      this.addField('State of Residence', form.stateOfResidence);
      this.addField('Patient Name', form.patientName);
      this.addField('Patient SSN', form.patientSsn);
      this.addField('Patient Date of Birth', this.formatDate(form.patientDob));
      this.addField('Patient Date of Death', this.formatDate(form.patientDod));
      this.addField('Requestor Name', form.requestorName);
      this.addField('Requestor Relationship', form.requestorRelationship);
      this.addField('Signature Date', this.formatDate(form.signatureDate));
    }

    // Certification of Identity
    if (this.supportingForms.certificationOfIdentity) {
      this.checkPageBreak(200);
      this.addSectionHeader('Certification of Identity');

      const form = this.supportingForms.certificationOfIdentity;
      this.addField('Full Name', form.fullName);
      this.addField('Citizenship Status', form.citizenshipStatus);
      this.addField('Social Security Number', form.ssn);
      this.addField('Current Address', form.currentAddress);
      this.addField('Date of Birth', this.formatDate(form.dob));
      this.addField('Place of Birth', form.placeOfBirth);
      this.addField('Signature Date', this.formatDate(form.signatureDate));

      if (form.authorizedPersonName) {
        this.currentY -= 15;
        this.drawText('Section 2: Authorized Representative', {
          x: this.margin + 10,
          y: this.currentY,
          size: 12,
          font: this.boldFont,
          color: COLORS.terracotta,
        });
        this.currentY -= 20;

        this.addField('Authorized Person Name', form.authorizedPersonName);
        this.addField('Relationship to Requester', form.relationshipToRequester);
        this.addField('Authorized Phone Number', form.authorizedPhoneNumber);
        this.addField('Authorized Current Address', form.authorizedCurrentAddress);
        this.addField('Authorized Signature Date', this.formatDate(form.authorizedSignatureDate));
      }
    }

    // Tribal Records Release
    if (this.supportingForms.tribalRecordsRelease) {
      this.checkPageBreak(150);
      this.addSectionHeader('Tribal Records Release');

      const form = this.supportingForms.tribalRecordsRelease;
      this.addField('Tribal Office', form.tribalOffice);
      if (form.otherTribalOffice) {
        this.addField('Other Tribal Office', form.otherTribalOffice);
      }
      this.addField('Claimant Name', form.claimantName);
      this.addField('Tribal Organization Name', form.tribalOrganizationName);
      this.addField('Signature Date', this.formatDate(form.signatureDate));
    }

    // Surviving Beneficiaries Signatures
    if (this.supportingForms.survivingBeneficiariesSignatures) {
      this.checkPageBreak(200);
      this.addSectionHeader('Surviving Beneficiaries Signatures');

      const form = this.supportingForms.survivingBeneficiariesSignatures;
      this.currentY -= 10;
      this.drawText(`Total Beneficiaries: ${form.beneficiaries.length}`, {
        x: this.margin + 10,
        y: this.currentY,
        size: 11,
        font: this.boldFont,
      });
      this.currentY -= 20;

      form.beneficiaries.forEach((beneficiary, index) => {
        this.currentY -= 10;
        this.drawText(`Beneficiary ${index + 1}:`, {
          x: this.margin + 10,
          y: this.currentY,
          size: 11,
          font: this.boldFont,
          color: COLORS.terracotta,
        });
        this.currentY -= 20;

        this.addField('Name', beneficiary.beneficiaryName);
        this.addField('SSN', beneficiary.beneficiarySsn);
        this.addField('Signature Date', this.formatDate(beneficiary.signatureDate));
        if (beneficiary.attorneyName) {
          this.addField('Attorney Name', beneficiary.attorneyName);
          this.addField('Attorney Phone', beneficiary.attorneyPhone);
        }
        this.currentY -= 10;
        this.checkPageBreak();
      });
    }
  }

  private async generateInstructionsPage() {
    this.addNewPage();
    this.currentY = this.pageHeight - 80;

    this.drawText('Next Steps: Completing Your RECA Claim', {
      x: this.margin,
      y: this.currentY,
      size: 20,
      font: this.boldFont,
      color: COLORS.terracotta,
    });

    this.currentY -= 40;

    const steps = [
      {
        number: '1',
        title: 'Review This Summary',
        description: 'Carefully review all information in this summary for accuracy.',
      },
      {
        number: '2',
        title: 'Print the Official Form',
        description: 'Print the official RECA Downwinder Claim Form included in your download.',
      },
      {
        number: '3',
        title: 'Fill Out the Official Form',
        description: 'Use this summary to transfer your information to the official form.',
      },
      {
        number: '4',
        title: 'Sign with Wet Signature',
        description: 'Sign the official form by hand (wet signature required by DOJ).',
      },
      {
        number: '5',
        title: 'Gather Supporting Documents',
        description: 'Collect required documents (birth certificates, medical records, etc.).',
      },
      {
        number: '6',
        title: 'Mail to Department of Justice',
        description: 'Send the completed form and documents to the address below.',
      },
    ];

    steps.forEach((step) => {
      this.drawBox({
        x: this.margin,
        y: this.currentY - 60,
        width: this.pageWidth - (2 * this.margin),
        height: 60,
        fillColor: rgb(0.97, 0.97, 0.97),
        borderColor: COLORS.sage,
      });

      // Step number circle
      this.currentPage.drawCircle({
        x: this.margin + 25,
        y: this.currentY - 30,
        size: 15,
        color: COLORS.terracotta,
      });

      this.drawText(step.number, {
        x: this.margin + 20,
        y: this.currentY - 35,
        size: 14,
        font: this.boldFont,
        color: COLORS.white,
      });

      this.drawText(step.title, {
        x: this.margin + 50,
        y: this.currentY - 20,
        size: 12,
        font: this.boldFont,
        color: COLORS.sage,
      });

      this.drawText(step.description, {
        x: this.margin + 50,
        y: this.currentY - 40,
        size: 10,
        color: COLORS.gray,
      });

      this.currentY -= 75;
    });

    // Mailing address
    this.currentY -= 20;
    this.drawBox({
      x: this.margin,
      y: this.currentY - 120,
      width: this.pageWidth - (2 * this.margin),
      height: 120,
      fillColor: rgb(0.95, 0.98, 1),
      borderColor: COLORS.sage,
    });

    this.currentY -= 20;
    this.drawText('Mail Your Completed Form To:', {
      x: this.margin + 10,
      y: this.currentY,
      size: 12,
      font: this.boldFont,
      color: COLORS.sage,
    });

    this.currentY -= 25;
    const addressLines = [
      'Radiation Exposure Compensation Program',
      'U.S. Department of Justice',
      'P.O. Box 146',
      'Ben Franklin Station',
      'Washington, DC 20044-0146',
    ];

    addressLines.forEach((line) => {
      this.drawText(line, {
        x: this.margin + 10,
        y: this.currentY,
        size: 11,
        color: COLORS.black,
      });
      this.currentY -= 16;
    });

    // Contact information
    this.currentY -= 30;
    this.drawText('Need Help?', {
      x: this.margin,
      y: this.currentY,
      size: 12,
      font: this.boldFont,
      color: COLORS.terracotta,
    });

    this.currentY -= 20;
    this.drawText('RECA Hotline: 1-800-729-7327', {
      x: this.margin,
      y: this.currentY,
      size: 11,
    });

    this.currentY -= 18;
    this.drawText('Website: www.justice.gov/civil/reca', {
      x: this.margin,
      y: this.currentY,
      size: 11,
    });
  }

  // Helper methods
  private addNewPage() {
    this.currentPage = this.pdfDoc.addPage([this.pageWidth, this.pageHeight]);
    this.currentY = this.pageHeight - this.margin;
  }

  private addSectionHeader(title: string) {
    this.checkPageBreak(60);
    this.currentY -= 25;

    this.drawBox({
      x: this.margin - 10,
      y: this.currentY - 25,
      width: this.pageWidth - (2 * this.margin) + 20,
      height: 35,
      fillColor: COLORS.sage,
    });

    this.drawText(title, {
      x: this.margin,
      y: this.currentY - 5,
      size: 14,
      font: this.boldFont,
      color: COLORS.white,
    });

    this.currentY -= 40;
  }

  private addField(label: string, value?: string | null) {
    if (!value && value !== '') return;

    this.checkPageBreak();

    this.drawText(`${label}:`, {
      x: this.margin + 10,
      y: this.currentY,
      size: 10,
      font: this.boldFont,
      color: COLORS.sage,
    });

    this.currentY -= 15;
    this.drawText(String(value), {
      x: this.margin + 20,
      y: this.currentY,
      size: 10,
      color: COLORS.black,
    });

    this.currentY -= 20;
  }

  private drawText(text: string, options: any) {
    const {
      x = this.margin,
      y = this.currentY,
      size = 10,
      font = this.font,
      color = COLORS.black,
    } = options;

    this.currentPage.drawText(text, {
      x,
      y,
      size,
      font,
      color,
    });
  }

  private drawBox(options: any) {
    const {
      x,
      y,
      width,
      height,
      fillColor = COLORS.white,
      borderColor,
      borderWidth = 1,
    } = options;

    if (fillColor) {
      this.currentPage.drawRectangle({
        x,
        y,
        width,
        height,
        color: fillColor,
      });
    }

    if (borderColor) {
      this.currentPage.drawRectangle({
        x,
        y,
        width,
        height,
        borderColor,
        borderWidth,
      });
    }
  }

  private checkPageBreak(requiredSpace: number = 80) {
    if (this.currentY < this.margin + requiredSpace) {
      this.addNewPage();
    }
  }

  private formatDate(dateString?: string | null): string {
    if (!dateString) return '';
    try {
      const date = new Date(dateString);
      return date.toLocaleDateString('en-US', {
        year: 'numeric',
        month: 'long',
        day: 'numeric',
      });
    } catch {
      return dateString;
    }
  }

  private formatDiseaseName(disease: string): string {
    const diseaseNames: Record<string, string> = {
      leukemia: 'Leukemia (except CLL)',
      multiple_myeloma: 'Multiple Myeloma',
      lymphomas: 'Lymphomas (except Hodgkin\'s)',
      thyroid: 'Thyroid Cancer',
      breast: 'Breast Cancer (female only)',
      esophagus: 'Esophageal Cancer',
      stomach: 'Stomach Cancer',
      pharynx: 'Pharyngeal Cancer',
      small_intestine: 'Small Intestine Cancer',
      pancreas: 'Pancreatic Cancer',
      bile_ducts: 'Bile Duct Cancer',
      gall_bladder: 'Gall Bladder Cancer',
      salivary_gland: 'Salivary Gland Cancer',
      urinary_bladder: 'Urinary Bladder Cancer',
      brain: 'Brain Cancer',
      colon: 'Colon Cancer',
      ovary: 'Ovarian Cancer',
      liver: 'Liver Cancer (primary only)',
      lung: 'Lung Cancer',
    };

    return diseaseNames[disease] || disease;
  }
}

// Export function to generate PDF
export async function generateRECAPDF(options: PDFGeneratorOptions): Promise<Uint8Array> {
  const generator = new RECAPDFGenerator(options);
  return await generator.generate();
}
